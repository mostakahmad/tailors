export function t(key, vars) {
  const table = STR[state.lang] || STR.en;
  let text = table[key] ?? STR.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function poseWarningText(warning) {
  if (!warning) return '';
  if (warning.code === 'missing_landmarks') {
    const parts = (warning.parts || []).map((id) => t(`part.${id}`)).join(', ');
    return t('pose.missing_landmarks', { parts });
  }
  return t(`pose.${warning.code}`);
}

export function sourceText(source) {
  if (source === 'manual_entry') return t('dash.sourceManual');
  if (source === 'verified_external_provider') return t('dash.sourceVerified');
  return t('dash.sourceDemo');
}

export function applyI18n() {
  document.documentElement.lang = state.lang === 'bn' ? 'bn' : 'en';
  document.title = t('meta.title');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  const themeBtn = document.getElementById('themeToggle');
  if (themeBtn) {
    const toDark = state.theme !== 'dark';
    themeBtn.setAttribute('aria-label', t(toDark ? 'nav.themeToDark' : 'nav.themeToLight'));
    themeBtn.setAttribute('aria-pressed', String(state.theme === 'dark'));
    const label = themeBtn.querySelector('[data-theme-label]');
    if (label) label.textContent = state.theme === 'dark' ? (state.lang === 'bn' ? 'লাইট' : 'Light') : (state.lang === 'bn' ? 'ডার্ক' : 'Dark');
  }
  const langBtn = document.getElementById('langToggle');
  if (langBtn) {
    langBtn.textContent = state.lang === 'bn' ? 'English' : 'বাংলা';
    langBtn.setAttribute('aria-label', state.lang === 'bn' ? 'Switch to English' : 'বাংলায় দেখুন');
  }
  const menu = document.getElementById('navToggle');
  if (menu) {
    const open = menu.getAttribute('aria-expanded') === 'true';
    menu.setAttribute('aria-label', t(open ? 'nav.menuClose' : 'nav.menu'));
  }
}

export function initI18n() {
  applyI18n();
  subscribe(() => applyI18n());
}
